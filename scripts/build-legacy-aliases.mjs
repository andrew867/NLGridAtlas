import { readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const inventory = JSON.parse(await readFile(path.join(root, "research", "derived", "ux-baseline-inventory.json"), "utf8"));
const pages = ["index.html", "network.html", "stations.html", "transmission.html", "loads.html", "history.html", "telephone.html", "telecom.html", "sources.html"];
const idsByPage = new Map();

for (const page of pages) {
  const html = await readFile(path.join(root, page), "utf8");
  idsByPage.set(page, new Set([...html.matchAll(/\s+id="([^"]+)"/g)].map((match) => match[1])));
}

const legacyTargets = [...new Set(inventory.localFragmentTargets)];
const aliases = {};
const unresolved = [];
const ambiguous = [];
const runtimeResolved = [];
const fixedResolved = new Set(["top", "main", "handbook", "network", "substations", "transmission", "timeline", "loads", "telephone", "telecom", "evidence"]);
for (const id of legacyTargets) {
  const owners = pages.filter((page) => idsByPage.get(page).has(id));
  if (owners.length === 1) aliases[id] = `./${owners[0]}#${id}`;
  else if (!owners.length && (/^(?:station|terminal|substation)-[A-Za-z0-9_-]+$/.test(id) || fixedResolved.has(id))) runtimeResolved.push(id);
  else if (!owners.length) unresolved.push(id);
  else if (fixedResolved.has(id)) runtimeResolved.push(id);
  else ambiguous.push({ id, owners });
}

const source = `// Generated by scripts/build-legacy-aliases.mjs.\nexport const generatedLegacyAliases = ${JSON.stringify(aliases, null, 2)};\n`;
await writeFile(path.join(root, "src", "navigation", "legacy-alias-map.js"), source, "utf8");
await writeFile(path.join(root, "research", "derived", "legacy-alias-audit.json"), `${JSON.stringify({
  schemaVersion: 1,
  generatedAt: "2026-11-17",
  baselineTargetCount: legacyTargets.length,
  mappedIdCount: Object.keys(aliases).length,
  runtimeResolvedCount: runtimeResolved.length,
  runtimeResolved,
  unresolvedIdCount: unresolved.length,
  unresolved,
  ambiguousIdCount: ambiguous.length,
  ambiguous
}, null, 2)}\n`, "utf8");
console.log(`Mapped ${Object.keys(aliases).length} of ${legacyTargets.length} legacy targets; ${runtimeResolved.length} use fixed or runtime aliases, ${unresolved.length} are unresolved, and ${ambiguous.length} have multiple owners.`);
